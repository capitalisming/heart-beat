#!/usr/bin/env python3
"""Software verification on SYNTHETIC signals (not a validation on people).

Runs three simulated experiments through the real evaluation code path and
writes everything to results/synthetic_verification/:

1. Agreement  - simulated "participants" breathing at known rates, evaluated
                exactly like a real study (manifest -> pipeline -> statistics).
2. Null       - pulses with no respiratory modulation at all: how often does
                the quality gate wrongly accept a window?
3. Noise sweep - error and coverage as measurement noise grows.

It also writes two small sample recordings in the firmware's file format to
data/sample/ so the command-line tools can be tried without hardware.

All numbers produced here describe the software on a parametric model. They
are not evidence that the method is accurate on human recordings.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

from _bootstrap import DEFAULT_CONFIG, REPO_ROOT

from ppg_resp.acquisition import recording_from_arrays
from ppg_resp.config import load_settings
from ppg_resp.evaluation import markdown_table, window_pairs
from ppg_resp.ground_truth import reference_from_events
from ppg_resp.pipeline import run_pipeline
from ppg_resp.reporting import write_evaluation_outputs
from ppg_resp.signal_quality import STATUS_OK
from ppg_resp.synthetic import SyntheticPPG, synthetic_ppg
from ppg_resp.visualization import save_recording_figures

RATES = (8.0, 12.0, 16.0, 20.0, 24.0)
N_PARTICIPANTS = 8
DURATION_S = 120.0
BANNER = (
    "> **SYNTHETIC DATA.** Every signal in this report was generated by `ppg_resp.synthetic`. "
    "The results verify the software against a known model. They are **not** a validation of the "
    "method on people and must not be quoted as its accuracy."
)


def simulate(participant: int, rr: float, seed: int, am_depth=None, noise_sd=None) -> SyntheticPPG:
    """One simulated recording; each 'participant' has its own heart rate, depth and noise."""
    rng = np.random.default_rng(1000 * participant + 7)
    return synthetic_ppg(
        duration_s=DURATION_S,
        fs_hz=100.0,
        hr_bpm=float(rng.uniform(58, 95)),
        rr_bpm=rr,
        am_depth=float(rng.uniform(0.05, 0.20)) if am_depth is None else am_depth,
        bw_depth=float(rng.uniform(0.0, 0.15)),
        fm_depth=float(rng.uniform(0.0, 0.04)),
        noise_sd=float(rng.uniform(0.01, 0.05)) if noise_sd is None else noise_sd,
        drift_depth=0.2,
        seed=seed,
        sensor_like=True,
    )


def write_sample(sim: SyntheticPPG, path: Path) -> None:
    """Save a simulated recording in the firmware stream format, with breath markers."""
    n = sim.values.size
    index = np.arange(n)
    marker = np.zeros(n, dtype=int)
    marker[np.clip(np.round(sim.breath_times_s * sim.fs_hz).astype(int), 0, n - 1)] = 1
    frame = pd.DataFrame(
        {
            "sample_index": index,
            "device_us": (index / sim.fs_hz * 1e6).astype(np.int64),
            "ir": np.round(sim.values).astype(int),
            "red": np.round(0.8 * sim.values).astype(int),
            "marker": marker,
        }
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        handle.write("# SYNTHETIC test signal generated by scripts/synthetic_verification.py - not a human recording\n")
        handle.write(f"# simulated breathing rate {sim.rr_bpm:g}/min, heart rate {sim.hr_bpm:.0f}/min\n")
        frame.to_csv(handle, index=False)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG)
    parser.add_argument("--outdir", type=Path, default=REPO_ROOT / "results" / "synthetic_verification")
    args = parser.parse_args(argv)
    settings = load_settings(args.config)
    out: Path = args.outdir

    # ---- 1. agreement study -------------------------------------------------
    pairs = []
    example = None
    for p in range(N_PARTICIPANTS):
        for rr in RATES:
            sim = simulate(p, rr, seed=100 * p + int(rr))
            result = run_pipeline(recording_from_arrays(sim.values, sim.fs_hz), settings)
            reference = reference_from_events(sim.breath_times_s, "simulated breath onsets")
            pairs.append(window_pairs(result, reference, f"SIM{p:02d}_rr{rr:.0f}", f"SIM{p:02d}", "S1", f"simulated {rr:.0f}/min"))
            if p == 0 and rr == 12.0:
                example = (result, reference)
    pairs = pd.concat(pairs, ignore_index=True)
    report = write_evaluation_outputs(
        pairs, out, "Synthetic verification - agreement with the simulated breathing rate",
        preamble=BANNER, figure_note=" — SYNTHETIC",
    )
    save_recording_figures(example[0], out / "figures" / "example_recording", example[1])

    # ---- 2. null experiment -------------------------------------------------
    null_rows = []
    for p in range(N_PARTICIPANTS):
        for rep in range(3):
            sim = simulate(p, 15.0, seed=5000 + 10 * p + rep, am_depth=0.0)
            sim_flat = synthetic_ppg(
                duration_s=DURATION_S, hr_bpm=sim.hr_bpm, am_depth=0.0, bw_depth=0.0, fm_depth=0.0,
                noise_sd=0.03, drift_depth=0.2, seed=5000 + 10 * p + rep, sensor_like=True,
            )
            result = run_pipeline(recording_from_arrays(sim_flat.values, sim_flat.fs_hz), settings)
            for w in result.windows:
                null_rows.append({"status": w.status, "sqi": w.sqi, "methods_agree": w.indicators.get("methods_agree")})
    null = pd.DataFrame(null_rows)
    null_accept = float((null["status"] == STATUS_OK).mean())
    null_accept_agree = float(((null["status"] == STATUS_OK) & (null["methods_agree"] == True)).mean())  # noqa: E712

    # ---- 3. noise sweep -----------------------------------------------------
    sweep_rows = []
    for noise in (0.0, 0.02, 0.05, 0.10, 0.20, 0.40):
        errors, accepted, total = [], 0, 0
        for p in range(N_PARTICIPANTS):
            for rr in (10.0, 18.0):
                sim = simulate(p, rr, seed=9000 + 10 * p + int(rr), am_depth=0.10, noise_sd=noise)
                result = run_pipeline(recording_from_arrays(sim.values, sim.fs_hz), settings)
                total += len(result.windows)
                for w in result.windows:
                    if w.status == STATUS_OK:
                        accepted += 1
                        errors.append(abs(w.rr_bpm - rr))
        sweep_rows.append(
            {
                "noise SD (pulse heights)": noise,
                "windows": total,
                "accepted %": 100.0 * accepted / total if total else float("nan"),
                "MAE of accepted (breaths/min)": float(np.mean(errors)) if errors else float("nan"),
                "max error of accepted": float(np.max(errors)) if errors else float("nan"),
            }
        )
    sweep = pd.DataFrame(sweep_rows)
    sweep.round(3).to_csv(out / "tables" / "noise_sweep.csv", index=False)
    null.to_csv(out / "tables" / "null_experiment_windows.csv", index=False)

    extra = [
        "", "## Null experiment (no respiratory modulation simulated)", "",
        f"- Windows analysed: {len(null)}",
        f"- Wrongly accepted by the quality gate (SQI >= {settings.quality.sqi_threshold:g}): "
        f"{100 * null_accept:.1f} %",
        f"- Wrongly accepted and all four methods agreeing within {settings.quality.agreement_tol_bpm:g} breaths/min: "
        f"{100 * null_accept_agree:.1f} %",
        "", "A clean pulse with no breathing information can still produce a spectral peak by chance. "
        "The quality gate reduces such false estimates but does not eliminate them.",
        "", "## Noise sweep (10 % amplitude modulation, rates 10 and 18 /min)", "",
        markdown_table(sweep, digits=2), "",
    ]
    with (out / "report.md").open("a", encoding="utf-8") as handle:
        handle.write("\n".join(extra))

    # ---- sample files for trying the tools ---------------------------------
    sample_dir = REPO_ROOT / "data" / "sample"
    for rr, hr in ((12.0, 68.0), (18.0, 82.0)):
        sim = synthetic_ppg(duration_s=90.0, hr_bpm=hr, rr_bpm=rr, am_depth=0.12, bw_depth=0.1, fm_depth=0.03,
                            noise_sd=0.02, drift_depth=0.2, seed=int(rr), sensor_like=True)
        write_sample(sim, sample_dir / f"SYNTHETIC_rr{rr:.0f}.csv")
    (sample_dir / "manifest.csv").write_text(
        "# Example study manifest. Both recordings are SYNTHETIC test signals.\n"
        "recording_id,participant_id,session_id,condition,ppg_file,fs_hz,channel,reference_type,reference_file,"
        "n_breaths,count_duration_s,time_offset_s,reference_source\n"
        "SYN_rr12,SYN01,S1,simulated_12,SYNTHETIC_rr12.csv,100,ir,markers,,,,,simulated markers\n"
        "SYN_rr18,SYN01,S1,simulated_18,SYNTHETIC_rr18.csv,100,ir,markers,,,,,simulated markers\n",
        encoding="utf-8",
    )

    m, c = report.recording_metrics, report.coverage
    print("SYNTHETIC verification (software check, not a validation on people)")
    print(f"  agreement : {m['n']} simulated recordings, MAE {m['mae']:.3f}, bias {m['bias']:+.3f} breaths/min, "
          f"{100 * c['accepted_fraction']:.1f} % of windows accepted")
    print(f"  null      : {100 * null_accept:.1f} % of {len(null)} no-modulation windows wrongly accepted")
    print(sweep.round(2).to_string(index=False))
    print(f"  report    : {out / 'report.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
